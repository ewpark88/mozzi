/// 모찌 표정 9종 (GDD §3 표정 9종). 어떤 순간에 어떤 표정인지는 P8 상태 머신이 정한다.
enum MochiExpression {
  /// 기본 (반짝 눈) — 대기, 메뉴.
  idle,

  /// 기대 (입 벌림) — 당기기 시작.
  expect,

  /// 긴장 (눈 질끈) — 최대로 당겼을 때.
  tense,

  /// 환희 (><) — 발사 순간.
  joy,

  /// 빵빵 (볼 부풀) — 씨앗 획득, 볼 부풀리기.
  puff,

  /// 어질 (@@) — 장애물 충돌.
  dizzy,

  /// 납작 — 착지 순간.
  flat,

  /// 뿌듯 (별 눈) — 신기록.
  proud,

  /// 분발 (콧김) — 짧은 기록.
  determined,
}
